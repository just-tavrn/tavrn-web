//! The tray icon (docs/DESKTOP.md "Tray"): the voice state of the client as the app logo with a status badge, a
//! tooltip with the channel and the state, and a menu: show/hide the window, mute, deafen, leave voice, quit. The
//! client's voice store drives it (`tray_set`, at most every 150 ms); the voice items of the menu go back to the client
//! as shell events. The five icons are drawn at start from the bundled logo (`icons/32x32.png`), so there are no
//! extra image files:
//!
//! | State | Icon |
//! |---|---|
//! | not in a voice channel | the plain logo |
//! | in a voice channel | green badge |
//! | speaking (push-to-talk or voice activation lets the voice through) | white badge with a green ring |
//! | microphone muted | amber badge with a bar |
//! | deafened (speakers and microphone; wins over muted) | red badge with a cross |
//!
//! Every badge has a dark outline, so it stands out on light panels and against the logo's teal; the shapes tell the
//! states apart without colour, and the tooltip names the state.
//!
//! "Close to tray" (Settings → App, default on everywhere): closing the window hides it; the tray menu or starting the
//! app again shows it, Quit (tray menu, Settings → App) ends the app.

use std::sync::{Mutex, OnceLock};

use serde::{Deserialize, Serialize};
use tauri::image::Image;
use tauri::menu::{CheckMenuItem, Menu, MenuItem, PredefinedMenuItem};
use tauri::tray::{MouseButton, MouseButtonState, TrayIcon, TrayIconBuilder, TrayIconEvent};
use tauri::{AppHandle, Manager, Runtime, State};

use crate::commands::Settings;
use crate::events::{self, ShellEvent, TrayAction};

/// The base of the tray icons (the logo, generated by `tauri icon` from web/public/icon-512.png).
const BASE_ICON: &[u8] = include_bytes!("../icons/32x32.png");
const MAX_LABEL: usize = 64;
const MAX_TOOLTIP: usize = 128;

#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum VoiceState {
    #[default]
    Disconnected,
    Connected,
    Speaking,
    Muted,
    Deafened,
}

/// The texts of the tray in the client's language.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Labels {
    pub tooltip: String,
    pub show: String,
    pub hide: String,
    pub mute: String,
    pub deafen: String,
    pub leave: String,
    pub quit: String,
}

impl Default for Labels {
    /// Until the client sends its texts.
    fn default() -> Self {
        Self {
            tooltip: "Tavrn".into(),
            show: "Show Tavrn".into(),
            hide: "Hide Tavrn".into(),
            mute: "Mute microphone".into(),
            deafen: "Deafen".into(),
            leave: "Leave voice channel".into(),
            quit: "Quit Tavrn".into(),
        }
    }
}

impl Labels {
    pub fn validate(&self) -> Result<(), &'static str> {
        let ok = |s: &str, max: usize| !s.trim().is_empty() && s.chars().count() <= max && !s.chars().any(char::is_control);
        let menu = [&self.show, &self.hide, &self.mute, &self.deafen, &self.leave, &self.quit];
        if ok(&self.tooltip, MAX_TOOLTIP) && menu.iter().all(|l| ok(l, MAX_LABEL)) { Ok(()) } else { Err("tray.invalid") }
    }
}

/// What the tray shows for a state.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct View {
    pub badge: Option<Badge>,
    pub mute_checked: bool,
    pub deafen_checked: bool,
    /// Mute, deafen and leave apply only in a voice channel or call.
    pub voice_items: bool,
}

/// The badge on the logo.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Badge {
    Connected,
    Speaking,
    Muted,
    Deafened,
}

pub fn view(state: VoiceState) -> View {
    let voice = |badge, mute_checked, deafen_checked| View { badge: Some(badge), mute_checked, deafen_checked, voice_items: true };
    match state {
        VoiceState::Disconnected => View { badge: None, mute_checked: false, deafen_checked: false, voice_items: false },
        VoiceState::Connected => voice(Badge::Connected, false, false),
        VoiceState::Speaking => voice(Badge::Speaking, false, false),
        VoiceState::Muted => voice(Badge::Muted, true, false),
        // Deafened mutes the microphone too (the client does both).
        VoiceState::Deafened => voice(Badge::Deafened, true, true),
    }
}

pub const OUTLINE: [u8; 4] = [0x0f, 0x17, 0x2a, 0xff];
pub const WHITE: [u8; 4] = [0xff, 0xff, 0xff, 0xff];
pub const GREEN: [u8; 4] = [0x16, 0xa3, 0x4a, 0xff];
pub const BRIGHT_GREEN: [u8; 4] = [0x22, 0xc5, 0x5e, 0xff];
pub const AMBER: [u8; 4] = [0xf5, 0x9e, 0x0b, 0xff];
pub const RED: [u8; 4] = [0xdc, 0x26, 0x26, 0xff];

/// Radius of the badge relative to the icon size.
const BADGE: f32 = 0.31;

/// The logo (RGBA, `width` × `height`) with the badge of `state` in the lower right corner.
pub fn badged(rgba: &[u8], width: u32, height: u32, state: VoiceState) -> Vec<u8> {
    let mut out = rgba.to_vec();
    let Some(badge) = view(state).badge else { return out };
    let size = width.min(height) as f32;
    let r = size * BADGE;
    let (cx, cy) = (width as f32 - r, height as f32 - r);
    let outline = (size / 24.0).max(1.0);
    let ring = (size / 12.0).max(1.0);
    let stroke = (size / 22.0).max(0.75);
    let mark = r * 0.55;
    for y in 0..height {
        for x in 0..width {
            let (dx, dy) = (x as f32 + 0.5 - cx, y as f32 + 0.5 - cy);
            let d = (dx * dx + dy * dy).sqrt();
            if d > r {
                continue;
            }
            let fill = match badge {
                Badge::Connected => GREEN,
                Badge::Speaking if d > r - outline - ring => BRIGHT_GREEN,
                Badge::Speaking => WHITE,
                Badge::Muted => AMBER,
                Badge::Deafened => RED,
            };
            let bar = badge == Badge::Muted && dy.abs() <= stroke && dx.abs() <= mark;
            let cross = badge == Badge::Deafened && dx.abs() <= mark && ((dx - dy).abs() <= stroke * 1.2 || (dx + dy).abs() <= stroke * 1.2);
            let px = if d > r - outline {
                OUTLINE
            } else if bar || cross {
                WHITE
            } else {
                fill
            };
            let i = ((y * width + x) * 4) as usize;
            if let Some(p) = out.get_mut(i..i + 4) {
                p.copy_from_slice(&px);
            }
        }
    }
    out
}

/// The icon of `state` for the tray.
pub fn icon(state: VoiceState) -> tauri::Result<Image<'static>> {
    static BASE: OnceLock<Option<Image<'static>>> = OnceLock::new();
    let base = BASE.get_or_init(|| Image::from_bytes(BASE_ICON).ok().map(|i| i.to_owned()));
    let Some(base) = base else { return Image::from_bytes(BASE_ICON).map(|i| i.to_owned()) };
    Ok(Image::new_owned(badged(base.rgba(), base.width(), base.height(), state), base.width(), base.height()))
}

struct Items<R: Runtime> {
    icon: TrayIcon<R>,
    window: MenuItem<R>,
    mute: CheckMenuItem<R>,
    deafen: CheckMenuItem<R>,
    leave: MenuItem<R>,
    quit: MenuItem<R>,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct Status {
    pub state: VoiceState,
    pub tooltip: String,
    /// The tray icon exists (false when the desktop offers no tray).
    pub available: bool,
    pub close_to_tray: bool,
}

/// The tray of the app and the state it shows.
pub struct Tray<R: Runtime> {
    items: Option<Items<R>>,
    current: Mutex<(VoiceState, Labels)>,
}

impl<R: Runtime> Tray<R> {
    /// Creates the tray icon; a desktop without a tray yields a tray that only keeps the state.
    pub fn create(app: &AppHandle<R>) -> Self {
        let items = build(app).map_err(|e| eprintln!("tavrn: no tray icon: {e}")).ok();
        Self { items, current: Mutex::new((VoiceState::Disconnected, Labels::default())) }
    }

    pub fn available(&self) -> bool {
        self.items.is_some()
    }

    fn apply(&self, state: VoiceState, labels: &Labels, window_visible: bool) -> tauri::Result<()> {
        let Some(items) = &self.items else { return Ok(()) };
        let v = view(state);
        items.icon.set_icon(Some(icon(state)?))?;
        items.icon.set_tooltip(Some(&labels.tooltip))?;
        items.window.set_text(if window_visible { &labels.hide } else { &labels.show })?;
        items.mute.set_text(&labels.mute)?;
        items.mute.set_checked(v.mute_checked)?;
        items.mute.set_enabled(v.voice_items)?;
        items.deafen.set_text(&labels.deafen)?;
        items.deafen.set_checked(v.deafen_checked)?;
        items.deafen.set_enabled(v.voice_items)?;
        items.leave.set_text(&labels.leave)?;
        items.leave.set_enabled(v.voice_items)?;
        items.quit.set_text(&labels.quit)?;
        Ok(())
    }

    pub fn set(&self, state: VoiceState, labels: Labels, window_visible: bool) -> Result<(), String> {
        labels.validate().map_err(str::to_string)?;
        let mut current = self.current.lock().map_err(|_| "tray.unavailable".to_string())?;
        self.apply(state, &labels, window_visible).map_err(|e| e.to_string())?;
        *current = (state, labels);
        Ok(())
    }

    /// The show/hide item follows the window.
    pub fn window_changed(&self, visible: bool) {
        let (Some(items), Ok(current)) = (&self.items, self.current.lock()) else { return };
        let _ = items.window.set_text(if visible { &current.1.hide } else { &current.1.show });
    }

    pub fn state(&self) -> (VoiceState, Labels) {
        self.current.lock().map(|c| c.clone()).unwrap_or_default()
    }
}

/// The main window is on screen (visible and not minimized).
pub fn window_visible<R: Runtime>(app: &AppHandle<R>) -> bool {
    app.get_webview_window(crate::MAIN_WINDOW).is_some_and(|w| w.is_visible().unwrap_or(false) && !w.is_minimized().unwrap_or(false))
}

/// Tells the tray that the window was shown or hidden.
pub fn window_changed<R: Runtime>(app: &AppHandle<R>) {
    if let Some(tray) = app.try_state::<Tray<R>>() {
        tray.window_changed(window_visible(app));
    }
}

/// Hides the main window (close to tray, the tray's "Hide").
pub fn hide_main<R: Runtime>(app: &AppHandle<R>) {
    if let Some(window) = app.get_webview_window(crate::MAIN_WINDOW) {
        let _ = window.hide();
    }
    window_changed(app);
}

fn build<R: Runtime>(app: &AppHandle<R>) -> tauri::Result<Items<R>> {
    let labels = Labels::default();
    let window = MenuItem::with_id(app, "window", &labels.hide, true, None::<&str>)?;
    let mute = CheckMenuItem::with_id(app, "mute", &labels.mute, false, false, None::<&str>)?;
    let deafen = CheckMenuItem::with_id(app, "deafen", &labels.deafen, false, false, None::<&str>)?;
    let leave = MenuItem::with_id(app, "leave", &labels.leave, false, None::<&str>)?;
    let quit = MenuItem::with_id(app, "quit", &labels.quit, true, None::<&str>)?;
    let menu = Menu::with_items(app, &[&window, &PredefinedMenuItem::separator(app)?, &mute, &deafen, &leave, &PredefinedMenuItem::separator(app)?, &quit])?;
    let icon = TrayIconBuilder::with_id("main")
        .icon(icon(VoiceState::Disconnected)?)
        .tooltip(&labels.tooltip)
        .menu(&menu)
        .show_menu_on_left_click(false)
        .on_menu_event(|app, event| match event.id().as_ref() {
            "window" if window_visible(app) => hide_main(app),
            "window" => events::show_main(app),
            "mute" => events::send(app, ShellEvent::Tray { action: TrayAction::Mute }),
            "deafen" => events::send(app, ShellEvent::Tray { action: TrayAction::Deafen }),
            "leave" => events::send(app, ShellEvent::Tray { action: TrayAction::Leave }),
            "quit" => app.exit(0),
            _ => {}
        })
        .on_tray_icon_event(|tray, event| {
            // Windows: a left click shows the window (Linux trays open the menu on any click).
            if let TrayIconEvent::Click { button: MouseButton::Left, button_state: MouseButtonState::Up, .. } = event {
                events::show_main(tray.app_handle());
            }
        })
        .build(app)?;
    Ok(Items { icon, window, mute, deafen, leave, quit })
}

/// "Close to tray" unless the settings say otherwise: on (the owner's choice for every platform).
pub fn close_to_tray_default() -> bool {
    true
}

/// Whether closing the window hides it into the tray (only with a tray icon).
pub fn closes_to_tray<R: Runtime>(app: &AppHandle<R>) -> bool {
    let available = app.try_state::<Tray<R>>().is_some_and(|t| t.available());
    let setting = app.try_state::<Settings>().and_then(|s| s.config.lock().ok().and_then(|c| c.close_to_tray));
    available && setting.unwrap_or_else(close_to_tray_default)
}

/// The client's voice state and the texts of the tray.
#[tauri::command]
pub fn tray_set(app: AppHandle, tray: State<'_, Tray<tauri::Wry>>, state: VoiceState, labels: Labels) -> Result<(), String> {
    tray.set(state, labels, window_visible(&app))
}

/// What the tray shows and whether closing hides the window (Settings → App; the smoke test).
#[tauri::command]
pub fn tray_status(app: AppHandle, tray: State<'_, Tray<tauri::Wry>>) -> Status {
    let (state, labels) = tray.state();
    Status { state, tooltip: labels.tooltip, available: tray.available(), close_to_tray: closes_to_tray(&app) }
}

/// Settings → App: close to tray on or off (persisted in the settings file).
#[tauri::command]
pub fn set_close_to_tray(settings: State<'_, Settings>, on: bool) -> Result<(), String> {
    crate::commands::update_config(&settings, |c| c.close_to_tray = Some(on))
}

/// Settings → App: quit the app (with close to tray, closing the window does not).
#[tauri::command]
pub fn quit_app(app: AppHandle) {
    app.exit(0);
}

#[cfg(test)]
mod tests {
    use super::*;

    const STATES: [VoiceState; 5] = [VoiceState::Disconnected, VoiceState::Connected, VoiceState::Speaking, VoiceState::Muted, VoiceState::Deafened];

    fn decoded() -> Image<'static> {
        Image::from_bytes(BASE_ICON).map(|i| i.to_owned()).unwrap_or_else(|e| unreachable!("app icon: {e}"))
    }

    fn pixel(rgba: &[u8], width: u32, x: u32, y: u32) -> [u8; 4] {
        let i = ((y * width + x) * 4) as usize;
        rgba.get(i..i + 4).and_then(|p| p.try_into().ok()).unwrap_or_default()
    }

    /// A square test image of one colour (the badge is drawn the same at every size).
    fn plain(size: u32, rgba: [u8; 4]) -> Vec<u8> {
        rgba.repeat((size * size) as usize)
    }

    #[test]
    fn states_map_to_badges_and_menu_states() {
        assert_eq!(view(VoiceState::Disconnected), View { badge: None, mute_checked: false, deafen_checked: false, voice_items: false });
        assert_eq!(view(VoiceState::Connected), View { badge: Some(Badge::Connected), mute_checked: false, deafen_checked: false, voice_items: true });
        assert_eq!(view(VoiceState::Speaking), View { badge: Some(Badge::Speaking), mute_checked: false, deafen_checked: false, voice_items: true });
        assert_eq!(view(VoiceState::Muted), View { badge: Some(Badge::Muted), mute_checked: true, deafen_checked: false, voice_items: true });
        assert_eq!(view(VoiceState::Deafened), View { badge: Some(Badge::Deafened), mute_checked: true, deafen_checked: true, voice_items: true });
    }

    #[test]
    fn the_client_sends_states_in_snake_case() -> serde_json::Result<()> {
        assert_eq!(serde_json::from_str::<VoiceState>(r#""deafened""#)?, VoiceState::Deafened);
        assert_eq!(serde_json::from_str::<VoiceState>(r#""speaking""#)?, VoiceState::Speaking);
        assert_eq!(serde_json::to_string(&VoiceState::Disconnected)?, r#""disconnected""#);
        assert!(serde_json::from_str::<VoiceState>(r#""shouting""#).is_err());
        Ok(())
    }

    #[test]
    fn five_distinct_icons_from_the_logo() {
        let base = decoded();
        let (w, h) = (base.width(), base.height());
        let icons: Vec<Vec<u8>> = STATES.iter().map(|s| badged(base.rgba(), w, h, *s)).collect();
        assert_eq!(icons[0], base.rgba(), "not in a voice channel: the plain logo");
        for (i, a) in icons.iter().enumerate() {
            assert_eq!(a.len(), (w * h * 4) as usize);
            for b in icons.iter().skip(i + 1) {
                assert_ne!(a, b);
            }
            assert_eq!(pixel(a, w, 2, 2), pixel(base.rgba(), w, 2, 2), "the upper left stays the logo");
        }
        for state in STATES {
            assert!(icon(state).is_ok());
        }
    }

    #[test]
    fn badges_stand_out_at_tray_sizes_on_light_and_dark_panels() {
        for size in [16u32, 22, 32] {
            for panel in [[0xff, 0xff, 0xff, 0xff], [0x20, 0x20, 0x20, 0xff], [0x1d, 0xe9, 0xb6, 0xff]] {
                let r = size as f32 * BADGE;
                let (cx, cy) = ((size as f32 - r) as u32, (size as f32 - r) as u32);
                let off_centre = cy - (r * 0.75) as u32;
                let draw = |s| badged(&plain(size, panel), size, size, s);
                let (connected, speaking, muted, deafened) =
                    (draw(VoiceState::Connected), draw(VoiceState::Speaking), draw(VoiceState::Muted), draw(VoiceState::Deafened));
                assert_eq!(pixel(&connected, size, cx, cy), GREEN, "{size}px");
                assert_eq!(pixel(&speaking, size, cx, cy), WHITE, "{size}px: speaking lights the badge up");
                assert_eq!(pixel(&muted, size, cx, cy), WHITE, "{size}px: the bar of muted");
                assert_eq!(pixel(&muted, size, cx, off_centre), AMBER, "{size}px");
                assert_eq!(pixel(&deafened, size, cx, cy), WHITE, "{size}px: the cross of deafened");
                assert_eq!(pixel(&deafened, size, cx, off_centre), RED, "{size}px");
                // The outline separates the badge from the panel or the logo: the badge's left edge is dark.
                let edge = (size as f32 - 2.0 * r + 0.6) as u32;
                assert_eq!(pixel(&connected, size, edge, cy), OUTLINE, "{size}px outline");
            }
        }
    }

    #[test]
    fn labels_are_bounded() {
        assert_eq!(Labels::default().validate(), Ok(()));
        let long = Labels { mute: "m".repeat(MAX_LABEL + 1), ..Labels::default() };
        assert_eq!(long.validate(), Err("tray.invalid"));
        let empty = Labels { quit: " ".into(), ..Labels::default() };
        assert_eq!(empty.validate(), Err("tray.invalid"));
        let control = Labels { tooltip: "Tavrn\u{1b}[31m".into(), ..Labels::default() };
        assert_eq!(control.validate(), Err("tray.invalid"));
        let german = Labels {
            tooltip: "Tavrn · Allgemein (Gaming) · Stummgeschaltet".into(),
            show: "Tavrn anzeigen".into(),
            hide: "Tavrn ausblenden".into(),
            mute: "Mikrofon stummschalten".into(),
            deafen: "Taub schalten".into(),
            leave: "Sprachkanal verlassen".into(),
            quit: "Tavrn beenden".into(),
        };
        assert_eq!(german.validate(), Ok(()));
    }

    #[test]
    fn close_to_tray_is_on_by_default() {
        assert!(close_to_tray_default());
    }
}
