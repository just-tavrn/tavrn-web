// Independent integration coverage: personal room groups, accessible member selection and Voice permissions.
import AxeBuilder from "@axe-core/playwright";
import { expect, test } from "@playwright/test";
import { NODE, createRoomViaApi, loginAs, openNavIfMobile, registerViaApi } from "./helpers";
import { joinRoom, openContextMenu } from "./menu-helpers";
import { scaled } from "./timeouts";

test("a plain member edits personal room groups without joining voice; suggestions and groups stay in that room", async ({ page, request }) => {
  test.setTimeout(scaled(120_000));
  const owner = await registerViaApi(request, "whown");
  const ownerAddress = `${owner.username}@localhost`;
  const member = await registerViaApi(request, "whmem");
  const outsider = await registerViaApi(request, "whout");
  const first = await createRoomViaApi(request, owner.token, "Whisper first");
  const second = await createRoomViaApi(request, owner.token, "Whisper second");
  await joinRoom(request, owner, first.id, member);
  await joinRoom(request, owner, second.id, member);
  await loginAs(page, member);
  await page.goto(`/rooms/${first.id}/settings/whisper`);
  await expect(page.getByRole("button", { name: "Neue Flüstergruppe", exact: true })).toBeVisible();
  await page.getByRole("textbox", { name: "Gruppenname", exact: true }).fill("Raid leaders");
  await page.getByRole("button", { name: "Neue Flüstergruppe", exact: true }).click();
  const group = page.getByRole("group", { name: "Raid leaders", exact: true });
  const search = group.getByRole("combobox");
  await search.fill(owner.username);
  await expect(group.getByRole("option")).toHaveCount(1);
  await expect(group.getByRole("option")).toContainText(owner.username);
  await search.press("ArrowDown");
  await search.press("Enter");
  await expect(group.getByRole("list")).toContainText(ownerAddress);
  await search.fill(owner.username);
  await expect(group.getByRole("option")).toHaveCount(0);
  await search.fill(member.username);
  await expect(group.getByRole("option")).toHaveCount(0);
  await search.fill(outsider.username);
  await expect(group.getByRole("option")).toHaveCount(0);
  await search.press("Escape");
  await group.getByRole("button", { name: `${ownerAddress} aus Gruppe entfernen`, exact: true }).click();
  await search.fill(owner.username);
  const suggestion = group.getByRole("option");
  if (test.info().project.use.hasTouch) await suggestion.tap();
  else await suggestion.click();
  await expect(group.getByRole("list")).toContainText(ownerAddress);
  const accessibility = await new AxeBuilder({ page }).include("main").withTags(["wcag2a", "wcag2aa", "wcag21aa"]).analyze();
  expect(accessibility.violations.map((v) => `${v.id}: ${v.nodes.map((n) => n.target.join(" ")).join(", ")}`)).toEqual([]);
  await test.info().attach(`whisper-settings-${test.info().project.name}`, { body: await page.screenshot(), contentType: "image/png" });
  await page.goto(`/rooms/${second.id}/settings/whisper`);
  await expect(page.getByRole("button", { name: "Neue Flüstergruppe", exact: true })).toBeVisible();
  await expect(page.getByRole("group", { name: "Raid leaders", exact: true })).toHaveCount(0);
  await page.goto(`/rooms/${first.id}/settings/whisper`);
  await expect(page.getByRole("group", { name: "Raid leaders", exact: true }).getByRole("list")).toContainText(ownerAddress);
  await page.goto(`/rooms/${first.id}`);
  await openNavIfMobile(page);
  await openContextMenu(page, page.getByTestId("voice-channel-link").first());
  await page.getByRole("menuitem", { name: /Flüster/ }).click();
  await expect(page).toHaveURL(new RegExp(`/rooms/${first.id}/settings/whisper$`));
  await expect(page.getByRole("group", { name: "Raid leaders", exact: true })).toBeVisible();
  await page.goto("/settings/voice");
  await expect(page.getByTestId("voice-settings")).toBeVisible();
  await expect(page.getByRole("button", { name: "Neue Flüstergruppe", exact: true })).toHaveCount(0);
  await expect(page.getByText("Weitere Tastenkürzel", { exact: true })).toBeVisible();
  await expect(page.getByText("Letztem Flüsternden antworten (halten)", { exact: true })).toBeVisible();
});


test("roles and channel overrides persist whisper initiation under the Voice category", async ({ page, request }) => {
  test.setTimeout(scaled(90_000));
  const owner = await registerViaApi(request, "whedit");
  const room = await createRoomViaApi(request, owner.token, "Whisper role editor");
  const voice = (room.channels as { id: string; kind: string }[]).find((c) => c.kind === "voice")!;
  const auth = { Authorization: `Bearer ${owner.token}` };
  const whisper = 1n << 41n;
  await loginAs(page, owner);
  await page.goto(`/rooms/${room.id}/settings/roles`);
  await page.getByTestId("role-list").getByRole("button", { name: /@everyone/ }).first().click();
  const roleEditor = page.getByTestId("role-editor");
  const voicePermissions = roleEditor.getByRole("group", { name: "Sprache", exact: true });
  const checkbox = voicePermissions.getByRole("checkbox", { name: /^Flüstern beginnen/ });
  await expect(checkbox).toBeChecked();
  await checkbox.uncheck();
  await roleEditor.getByRole("button", { name: "Speichern", exact: true }).click();
  await expect(page.getByRole("status").filter({ hasText: "Rolle gespeichert" })).toBeVisible();
  const detail = await (await request.get(`${NODE}/api/v1/rooms/${room.id}`, { headers: auth })).json();
  const everyone = (detail.roles as { id: string; is_everyone: boolean; permissions: string }[]).find((r) => r.is_everyone)!;
  expect(BigInt(everyone.permissions) & whisper).toBe(0n);
  await page.goto(`/rooms/${room.id}/settings/channels`);
  await page.getByTestId("channel-tree-row").and(page.locator(`[data-channel="${voice.id}"]`)).getByRole("button").first().click();
  const channelEditor = page.getByTestId("channel-editor");
  const channelVoice = channelEditor.locator('fieldset[data-group="voice"]');
  await expect(channelVoice.locator("legend")).toHaveText("Sprache");
  await channelVoice.getByRole("radio", { name: "Flüstern beginnen: erlauben", exact: true }).click();
  await channelEditor.getByRole("button", { name: "Berechtigungen speichern", exact: true }).click();
  await expect(page.getByRole("status").filter({ hasText: "Berechtigungen gespeichert" })).toBeVisible();
  await page.reload();
  await page.getByTestId("channel-tree-row").and(page.locator(`[data-channel="${voice.id}"]`)).getByRole("button").first().click();
  await expect(page.getByTestId("channel-editor").getByRole("radio", { name: "Flüstern beginnen: erlauben", exact: true })).toHaveAttribute("aria-checked", "true");
});
